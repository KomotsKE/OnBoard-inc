import { describe, expect, it } from "vitest";

import { toursLabel } from "./ProjectsPage";

describe("число туров словами", () => {
  it("склоняется по правилам русского счёта", () => {
    // Машинное «2 тур(ов)» в интерфейсе владельца выглядит как недоделка.
    expect([0, 1, 2, 4, 5, 11, 14, 21, 22, 25, 101, 112].map(toursLabel)).toEqual([
      "0 туров",
      "1 тур",
      "2 тура",
      "4 тура",
      "5 туров",
      "11 туров",
      "14 туров",
      "21 тур",
      "22 тура",
      "25 туров",
      "101 тур",
      "112 туров",
    ]);
  });
});
